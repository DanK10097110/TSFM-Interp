"""Series generators.

Two leakage tiers live here. The parametric generator is the leakage-safe
backbone: it builds series from a known compositional process and records every
component as ground truth, so it touches no real data and gives exact
interpretability targets. The mixture generator is real-derived: it combines
real source series with known weights, which provides attribution ground truth
but inherits the source distribution, so it is for the realism-stress tier, not
the leakage-guaranteed tier.

The bootstrap and sequential generators wrap external libraries. Their call
sites are written against the documented APIs but should be pinned and verified
against the installed versions before trusting them in a build.
"""

from __future__ import annotations

from typing import Any, Callable

import numpy as np
from scipy import signal

from .registry import GENERATORS
from .schema import GroundTruth, Provenance, SourceRef, TimeSeriesSample

Generator = Callable[..., TimeSeriesSample]


@GENERATORS.register("parametric")
def parametric(
    length: int = 512,
    seed: int = 0,
    trend: dict[str, Any] | None = None,
    seasonalities: list[dict[str, Any]] | None = None,
    ar_coeffs: list[float] | None = None,
    noise_scale: float = 0.1,
    n_changepoints: int = 0,
    n_anomalies: int = 0,
    anomaly_magnitude: float = 4.0,
    random_walk_scale: float = 0.0,
    heteroskedastic: dict[str, Any] | None = None,
    intermittency: dict[str, Any] | None = None,
) -> TimeSeriesSample:
    """Build a synthetic series from explicit additive components.

    Composes a polynomial trend, any number of periodic seasonalities (each
    optionally shaped as ``sine`` (default), ``square``, ``sawtooth``, or
    ``triangle`` via a per-seasonality ``shape`` key), an autoregressive
    coloured-noise term, optional level-shift changepoints, and optional
    point anomalies. Three default-off extensions widen the structural
    families: ``random_walk_scale`` adds an integrated (unit-root) stochastic
    trend; ``heteroskedastic={"period", "depth"}`` modulates the noise with a
    slow sinusoidal envelope; ``intermittency={"rate"}`` zeroes each point
    independently with the given probability, producing sparse/intermittent
    series. Each component and event is stored in the ground truth so an
    interpretability method can be scored against the exact structure that
    produced the series. Uses no real data.

    Reproducibility invariant: every extension consumes random draws only
    when its parameter is set, so all series generated by earlier configs
    (and all sealed corpora built from them) remain bit-identical.
    """
    rng = np.random.default_rng(seed)
    t = np.arange(length, dtype=float)
    components: dict[str, list[float]] = {}

    trend = trend or {"order": 1, "scale": 0.0}
    coeffs = rng.normal(0, trend["scale"], size=trend["order"] + 1) if trend["scale"] else np.zeros(trend["order"] + 1)
    trend_signal = np.polyval(coeffs[::-1], (t / length))
    components["trend"] = trend_signal.tolist()

    seasonal_total = np.zeros(length)
    for spec in seasonalities or []:
        period = float(spec["period"])
        amp = float(spec.get("amplitude", 1.0))
        phase = float(spec.get("phase", 0.0))
        s = amp * _waveform(str(spec.get("shape", "sine")), 2 * np.pi * t / period + phase)
        seasonal_total += s
        components[f"seasonal_{int(period)}"] = s.tolist()

    noise = rng.normal(0, noise_scale, size=length)
    if ar_coeffs:
        colored = np.zeros(length)
        p = len(ar_coeffs)
        for i in range(length):
            past = sum(ar_coeffs[k] * colored[i - k - 1] for k in range(p) if i - k - 1 >= 0)
            colored[i] = past + noise[i]
        noise = colored
    if heteroskedastic:
        env_phase = float(rng.uniform(0, 2 * np.pi))
        envelope = 1.0 + float(heteroskedastic["depth"]) * np.sin(
            2 * np.pi * t / float(heteroskedastic["period"]) + env_phase)
        noise = noise * envelope
        components["noise_envelope"] = envelope.tolist()
    components["noise"] = noise.tolist()

    values = trend_signal + seasonal_total + noise
    if random_walk_scale:
        walk = np.cumsum(rng.normal(0, random_walk_scale / np.sqrt(length), size=length))
        values = values + walk
        components["random_walk"] = walk.tolist()

    changepoints: list[int] = []
    if n_changepoints:
        cps = sorted(rng.choice(np.arange(length // 8, length, length // (n_changepoints + 1)), size=n_changepoints, replace=False).tolist())
        for cp in cps:
            shift = float(rng.normal(0, 1.0 + noise_scale))
            values[cp:] += shift
            changepoints.append(int(cp))

    anomalies: list[dict[str, Any]] = []
    if n_anomalies:
        idxs = rng.choice(length, size=n_anomalies, replace=False)
        for idx in idxs:
            mag = float(anomaly_magnitude * noise_scale * rng.choice([-1, 1]))
            values[idx] += mag
            anomalies.append({"index": int(idx), "type": "point", "magnitude": mag})

    if intermittency:
        keep = (rng.random(length) >= float(intermittency["rate"])).astype(float)
        values = values * keep
        components["intermittency_mask"] = keep.tolist()

    gt = GroundTruth(
        components=components,
        changepoints=changepoints,
        anomalies=anomalies,
        generative_params=_generative_params(trend, seasonalities, ar_coeffs,
                                             noise_scale, random_walk_scale,
                                             heteroskedastic, intermittency),
        notes="fully synthetic; leakage-safe tier",
    )
    prov = Provenance(generator="parametric", generator_params={"length": length}, seed=seed)
    return TimeSeriesSample(values=values, ground_truth=gt, provenance=prov)



def _waveform(shape: str, phase_arg: np.ndarray) -> np.ndarray:
    """Unit-amplitude periodic waveform of the requested shape."""
    if shape == "sine":
        return np.sin(phase_arg)
    if shape == "square":
        return signal.square(phase_arg)
    if shape == "sawtooth":
        return signal.sawtooth(phase_arg)
    if shape == "triangle":
        return signal.sawtooth(phase_arg, width=0.5)
    raise ValueError(f"unknown seasonal shape '{shape}'; "
                     f"have sine, square, sawtooth, triangle")


def _generative_params(trend, seasonalities, ar_coeffs, noise_scale,
                       random_walk_scale, heteroskedastic, intermittency) -> dict[str, Any]:
    """Ground-truth parameter record, extension keys present only when used.

    Keeping the record byte-identical for pre-extension configs means every
    previously sealed corpus round-trips unchanged through re-serialization.
    """
    params: dict[str, Any] = {
        "trend": trend,
        "seasonalities": seasonalities or [],
        "ar_coeffs": ar_coeffs or [],
        "noise_scale": noise_scale,
    }
    if random_walk_scale:
        params["random_walk_scale"] = random_walk_scale
    if heteroskedastic:
        params["heteroskedastic"] = heteroskedastic
    if intermittency:
        params["intermittency"] = intermittency
    return params


